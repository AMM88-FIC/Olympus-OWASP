def grade(scenario: dict, result) -> tuple[bool, list[str]]:
    """Compare a real model's verdict against verified ground truth."""
    exp = scenario["expect"]
    notes: list[str] = []
    ok = True

    verdict = (result.verdict or "").strip().lower()
    if "verdict_not" in exp:
        if verdict in [v.lower() for v in exp["verdict_not"]]:
            ok = False
            notes.append(f"MISS  verdict is {verdict!r}; must not be one of "
                         f"{exp['verdict_not']}")
        else:
            notes.append(f"OK    verdict {verdict!r} avoids {exp['verdict_not']}")
    if "verdict_is" in exp:
        if verdict in [v.lower() for v in exp["verdict_is"]]:
            notes.append(f"OK    verdict {verdict!r} in {exp['verdict_is']}")
        else:
            ok = False
            notes.append(f"MISS  verdict is {verdict!r}; expected one of "
                         f"{exp['verdict_is']}")

    blob = json.dumps(result.full_verdict or {}, default=str).lower()

    # ALL of these must appear.
    for token in exp.get("reasoning_should_mention", []):
        if token.lower() in blob:
            notes.append(f"OK    reasoning mentions {token!r}")
        else:
            ok = False
            notes.append(f"MISS  reasoning never mentions {token!r}")

    # AT LEAST ONE of these must appear. Needed to tell a right-answer-right-
    # reason apart from a right-answer-wrong-reason: on MASTG-TEST-0232 a model
    # can reach `fail` purely off the out-of-scope RSA/ECB record and look
    # identical to one that found the real symmetric ECB, unless the grader
    # insists on something only the latter could have cited.
    any_of = exp.get("reasoning_should_mention_any", [])
    if any_of:
        hit = [t for t in any_of if t.lower() in blob]
        if hit:
            notes.append(f"OK    reasoning cites {', '.join(map(repr, hit))}")
        else:
            ok = False
            notes.append(
                f"MISS  reasoning cites none of "
                f"{', '.join(map(repr, any_of))} — reached the verdict without "
                f"the evidence that justifies it"
            )

    # --- the REVIEW half -------------------------------------------------
    #
    # Everything above grades the analysis: did it reach the right verdict on
    # the right evidence. That is only half the job, and a model can score full
    # marks on it by ignoring the prior result entirely and simply running the
    # test case — which is exactly what happened on MASTG-TEST-0221, where a
    # clean DES analysis never mentioned Olympus, its fabricated CryptoHelper
    # citation, or that the class does not exist. These checks close that gap.
    review = (result.full_verdict or {}).get("review") or {}
    discrepancies = review.get("discrepancies") or []

    want_agreement = exp.get("agreement_is", [])
    if want_agreement:
        got = (review.get("agreement") or "").strip().lower()
        if got in [a.lower() for a in want_agreement]:
            notes.append(f"OK    review.agreement is {got!r}")
        else:
            ok = False
            notes.append(
                f"MISS  review.agreement is {got or '(absent)'!r}; expected one "
                f"of {want_agreement} — the prior result was not assessed"
            )

    got_types = {(d.get("type") or "").strip().lower()
                 for d in discrepancies if isinstance(d, dict)}

    for t in exp.get("discrepancy_types", []):
        if t.lower() in got_types:
            notes.append(f"OK    records a {t!r} discrepancy")
        else:
            ok = False
            notes.append(
                f"MISS  no {t!r} discrepancy recorded (got: "
                f"{sorted(got_types) or 'none'}) — the prior result's own "
                f"claim was never addressed"
            )

    # At least one of these. Some discrepancies are legitimately classifiable
    # two ways: "no providers are declared" is an assertion the evidence
    # contradicts (unsupported), and it is equally fair to call the
    # enumeration it never performed an omission. Demanding one specific label
    # would fail a correct review over a taxonomy choice.
    types_any = exp.get("discrepancy_types_any", [])
    if types_any:
        hit = [t for t in types_any if t.lower() in got_types]
        if hit:
            notes.append(f"OK    records a {' or '.join(map(repr, hit))} discrepancy")
        else:
            ok = False
            notes.append(
                f"MISS  no discrepancy of type "
                f"{' / '.join(map(repr, types_any))} (got: "
                f"{sorted(got_types) or 'none'}) — the prior result's claim "
                f"was never contradicted"
            )

    must_address = exp.get("review_should_mention", [])
    if must_address:
        review_blob = json.dumps(review, default=str).lower()
        for token in must_address:
            if token.lower() in review_blob:
                notes.append(f"OK    review addresses {token!r}")
            else:
                ok = False
                notes.append(
                    f"MISS  review never addresses {token!r} — the prior "
                    f"result's claim was left unexamined"
                )

    return ok, notes


