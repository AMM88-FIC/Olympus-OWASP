#!/usr/bin/env python3
"""
demo_olympus_validation.py — exercise the Olympus gap reviewer.

It answers two DIFFERENT questions, and they must not be confused:

  1. "Does the integration work?"      -> default   (no LLM, runs anywhere)
  2. "Does the LLM catch the problem?" -> --real     (needs a real model)

**The default mode cannot answer question 2.** The scripted reviewer's answer is
written into this file, so grading it would be grading my own hard-coding. It
proves wiring: config, session handshake, evidence delivery, tool calls, verdict
parsing, output paths. Nothing about reasoning.

`--real` runs the actual model and then GRADES its verdict against ground truth
verified by hand against this app's evidence files.

Scenarios (`--list-scenarios`):

  fabricated   Olympus reports DES at a class that does not exist — but the app
               really does use DES elsewhere. Does the reviewer reject the bad
               citation AND still find the real finding?
  overclaim    Olympus fails the app over RSA/ECB/PKCS1Padding. RSA is
               asymmetric, so out of scope for a symmetric-mode test. Does the
               reviewer catch the false positive?
  thin         Olympus passes the app citing one AES/CBC call site, never
               mentioning the other seven cipher configurations or the RSA/ECB
               record. The verdict is right; the basis is incomplete. Does the
               reviewer notice what was never examined?

Examples:

    python demo_olympus_validation.py --list-scenarios
    python demo_olympus_validation.py --scenario thin
    python demo_olympus_validation.py --scenario thin --real --config config.ini
    python demo_olympus_validation.py --scenario all  --real --config config.ini
"""

