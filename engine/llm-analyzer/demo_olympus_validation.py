def _mod(name, **attrs):
    import types
    m = types.ModuleType(name)
    for k, v in attrs.items():
        setattr(m, k, v)
    return m


def _stub_missing_sdks() -> list[str]:
    """The scripted path needs no LLM SDK. Stub only what is genuinely absent,
    so the demo runs on a bare checkout."""
    import types
    stubbed = []
    try:
        import ujson  # noqa: F401
    except ImportError:
        sys.modules["ujson"] = _mod("ujson", dumps=json.dumps, loads=json.loads,
                                    JSONDecodeError=ValueError)
        stubbed.append("ujson")
    try:
        import openai  # noqa: F401
    except ImportError:
        sys.modules["openai"] = _mod("openai", OpenAI=object)
        stubbed.append("openai")
    try:
        from google import genai  # noqa: F401
    except ImportError:
        g, gg = types.ModuleType("google"), types.ModuleType("google.genai")
        gg.types = types.ModuleType("google.genai.types")
        g.genai = gg
        sys.modules.update({"google": g, "google.genai": gg,
                            "google.genai.types": gg.types})
        stubbed.append("google-genai")
    return stubbed


def rule(title: str = "") -> None:
    print("\n" + "=" * 76)
    if title:
        print(f"  {title}")
        print("=" * 76)


def wrap(text: str, indent: str = "  ") -> str:
    import textwrap
    return "\n".join(indent + ln for ln in
                     textwrap.wrap(" ".join(str(text).split()), 74))


def run_one(name: str, args, engine_factory) -> bool:
    from app.engine_api import EngineError

    scenario = SCENARIOS[name]
    rule(f"SCENARIO: {name}   ({scenario['test_id']})")
    print(wrap(scenario["summary"]))
    print("\n  Verified ground truth (checked by hand against the evidence):")
    print(wrap(scenario["ground_truth"], "    "))

    rule("1. What Olympus (faked) reported")
    print(json.dumps(scenario["olympus_output"], indent=2))

    engine = engine_factory()
    rule("2. Reviewer session")
    backend = None if args.real else ScriptedReviewer(scenario)
    if args.real:
        print(f"  MODE: real model ({engine.settings['model']})")
        print(f"        reviewer prompt: "
              f"{Path(engine.validation_mode.system_prompt).name}")
        print(f"        reviewer schema: "
              f"{Path(engine.validation_mode.schema).name}")
    else:
        print("  MODE: scripted — WIRING TEST ONLY.")
        print("        The answer below is hard-coded in this file. It shows")
        print("        the integration working end to end; it says nothing")
        print("        about whether a model would reason this way.")
    print()

    try:
        result = engine.validate(
            scenario["test_id"],
            scenario["olympus_output"],
            backend=backend,
            system_prompt=args.system_prompt,
        )
    except EngineError as exc:
        print(f"\nERROR: {exc}", file=sys.stderr)
        return False

    if args.show_prompt and backend is not None and len(backend.turns) >= 3:
        rule("2b. Prompt the reviewer received")
        print(backend.turns[2])

    rule("3. Result")
    prior = scenario["olympus_output"]
    prior_verdict = (prior.get("verdict") if isinstance(prior, dict)
                     else (result.olympus.verdict if result.olympus else None))
    print(f"  Olympus verdict  : {prior_verdict or '(unparsed from text)'}")
    print(f"  Reviewer verdict : {result.verdict}  (certainty {result.certainty})")
    print(f"  status           : {result.status}")
    print(f"  disagreed        : {result.gaps_found}")
    if result.output_path:
        print(f"  written to       : {result.output_path}")
    if result.rationale:
        print("\n  Rationale:")
        print(wrap(result.rationale, "    "))

    rule("4. Assessment")
    if not args.real:
        print("  NOT GRADED — a scripted answer is not evidence about a model.")
        print("  To grade real reasoning:")
        print(f"    python {Path(__file__).name} --scenario {name} --real "
              f"--config config.ini")
        print("\n  What a good real answer looks like:")
        print(wrap(scenario["expect"]["good"], "    "))
        print("\n  What a failure looks like:")
        print(wrap(scenario["expect"]["bad"], "    "))
        return True

    passed, notes = grade(scenario, result)
    for note in notes:
        print(f"  {note}")
    print(f"\n  => {'PASS' if passed else 'FAIL'}: the model "
          f"{'handled' if passed else 'did not handle'} this scenario.")
    if not passed:
        print("\n  Expected behaviour:")
        print(wrap(scenario["expect"]["good"], "    "))
    return passed


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Exercise the Olympus gap reviewer against faked output.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--scenario", default="thin",
                    help="Scenario name, or 'all'. Default: thin")
    ap.add_argument("--list-scenarios", action="store_true")
    ap.add_argument("--apk-root", type=Path, default=DEFAULT_JOB)
    ap.add_argument("--test-plan-dir", type=Path,
                    default=REPO / "app/layer4/test_plans/owasp_mastg")
    ap.add_argument("--real", action="store_true",
                    help="Use a real LLM and grade its reasoning.")
    ap.add_argument("--config", type=Path, default=REPO / "config.ini")
    ap.add_argument("--system-prompt", type=Path, default=None,
                    help="Validation-scoped system prompt (TODO H1).")
    ap.add_argument("--show-prompt", action="store_true")
    args = ap.parse_args()

    if args.list_scenarios:
        print("\nScenarios:\n")
        for nm, sc in SCENARIOS.items():
            print(f"  {nm:12} {sc['test_id']}  {sc['summary']}")
        print("\n  --real grades the model against verified ground truth.")
        print("  Without --real, only the wiring is exercised.\n")
        return 0

    names = list(SCENARIOS) if args.scenario == "all" else [args.scenario]
    unknown = [n for n in names if n not in SCENARIOS]
    if unknown:
        print(f"Unknown scenario(s): {', '.join(unknown)}. "
              f"Available: {', '.join(SCENARIOS)}, all", file=sys.stderr)
        return 2

    if not args.real:
        stubbed = _stub_missing_sdks()
        if stubbed:
            print(f"(no LLM needed — stubbed absent SDKs: {', '.join(stubbed)})")
    if args.system_prompt is None:
        pass

    from app.engine_api import EngineAPI, EngineMode, EngineSettings

    apk_root = args.apk_root.resolve()
    if not (apk_root / "evidence").is_dir():
        print(f"ERROR: no evidence directory under {apk_root}", file=sys.stderr)
        return 2

    def engine_factory():
        if args.real:
            # Build the engine the way Olympus does: deployment settings from
            # wherever the host keeps them, and the VALIDATION mode passed
            # explicitly.
            #
            # This used to be EngineAPI.from_config_file(...), which takes
            # system_prompt and schema straight from the INI — and every INI in
            # this repo points at the ANALYSIS prompt. So --real ran the
            # reviewer with the analyser's system prompt: the model was never
            # told it was reviewing a prior result, never told a `review` block
            # existed, and produced a clean test-case analysis with no review in
            # it. The grader then reported PASS. Mode selection is the whole
            # point of EngineMode; the demo was bypassing it.
            if not VALIDATION_PROMPT.is_file() or not VALIDATION_SCHEMA.is_file():
                print(
                    f"ERROR: the reviewer prompt/schema are missing:\n"
                    f"         {VALIDATION_PROMPT}\n"
                    f"         {VALIDATION_SCHEMA}\n"
                    f"       Generate them:  python tools/build_validation_prompts.py",
                    file=sys.stderr)
                raise SystemExit(2)
            return EngineSettings.from_config_file(args.config).for_apk(
                apk_root,
                evidence_dir=apk_root / "evidence",
                test_plan_dir=args.test_plan_dir,
                validation=EngineMode(
                    "validation", VALIDATION_PROMPT, VALIDATION_SCHEMA),
            )
        settings = EngineSettings.from_dict({
            "backend": "openai", "model": "scripted",
            "base_url": "http://localhost:0",
            # The scripted path uses the REVIEWER prompt and schema too, so
            # the wiring test exercises the same files --real does. Using the
            # analysis prompt here meant the two paths delivered different
            # system prompts and different schemas, which is exactly the
            # mismatch that made a reviewer run produce no review block.
            "system_prompt": VALIDATION_PROMPT,
            "schema": VALIDATION_SCHEMA,
        })
        return settings.for_apk(
            apk_root, test_plan_dir=args.test_plan_dir,
            evidence_dir=apk_root / "evidence",
            output_dir=REPO / "storage" / "verdicts" / "demo-validation",
        )

    results = {n: run_one(n, args, engine_factory) for n in names}

    if len(results) > 1:
        rule("SUMMARY")
        for n, ok in results.items():
            print(f"  {'PASS' if ok else 'FAIL'}  {n}")
        if args.real:
            print(f"\n  {sum(results.values())}/{len(results)} scenarios handled.")
    rule()
    return 0 if all(results.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
